// Clawdling's dedicated tmux server: one-shot commands plus control-mode clients.
//
// Facts verified on tmux 3.6a that shape this file:
// - `set -g window-size manual` in the config file crashes the server at start, so window-size
//   is set per session right after new-session instead.
// - `set-option -t =name` fails ("no such session"); pane/window targets need `=name:`.
// - tmux strips a trailing `;` from any argv element (it is a command separator), so no user text
//   is ever passed to tmux as an argument: sessions run a generated launcher script instead.
// - In control mode, `%output %<pane> <data>` escapes bytes < 0x20 and `\` as \ooo octal; a UTF-8
//   character can be split across two %output lines; each command we write gets its own
//   %begin/%end block with flags=1 (flags=0 blocks are tmux's own, e.g. the attach itself).
import { spawn } from 'node:child_process';
import { EventEmitter } from 'node:events';
import crypto from 'node:crypto';
import fs from 'node:fs';
import { tmuxInstallHint } from './hints.js';
import { which } from './paths.js';
import { buildSnapshot } from './termfilter.js';
import { execFileP, writeFileAtomic } from './util.js';

export const TMUX_CONF = `# Generated by Clawdling. Only read by Clawdling's own tmux server (tmux -L <socket>),
# never by your normal tmux. Regenerated on every start.
set -g history-limit 50000
set -g status off
set -g remain-on-exit off
set -g default-terminal "screen-256color"
set -g escape-time 10
set -g set-titles off
set -g allow-rename off
set -g mouse off
set -g focus-events on
`;

/** Split a byte stream into lines on 0x0a without ever decoding (keeps UTF-8 intact). */
export class LineSplitter {
  constructor() {
    this.parts = [];
  }

  push(chunk) {
    const out = [];
    let start = 0;
    for (;;) {
      const nl = chunk.indexOf(0x0a, start);
      if (nl === -1) break;
      let line = chunk.subarray(start, nl);
      if (this.parts.length) {
        this.parts.push(line);
        line = Buffer.concat(this.parts);
        this.parts = [];
      }
      out.push(line);
      start = nl + 1;
    }
    if (start < chunk.length) this.parts.push(Buffer.from(chunk.subarray(start)));
    return out;
  }
}

/** Undo tmux's \ooo octal escaping at the byte level. */
export function unescapeOctal(buf) {
  if (buf.indexOf(0x5c) === -1) return buf;
  const out = Buffer.allocUnsafe(buf.length);
  let o = 0;
  for (let i = 0; i < buf.length; i++) {
    const b = buf[i];
    if (b === 0x5c && i + 3 < buf.length) {
      const d1 = buf[i + 1] - 0x30;
      const d2 = buf[i + 2] - 0x30;
      const d3 = buf[i + 3] - 0x30;
      if (d1 >= 0 && d1 <= 3 && d2 >= 0 && d2 <= 7 && d3 >= 0 && d3 <= 7) {
        out[o++] = (d1 << 6) | (d2 << 3) | d3;
        i += 3;
        continue;
      }
    }
    out[o++] = b;
  }
  return out.subarray(0, o);
}

/** Parse one control-mode line that is not inside a command response block. */
export function parseControlLine(line) {
  if (line.length === 0 || line[0] !== 0x25) return { type: 'data', raw: line };
  const sp = line.indexOf(0x20);
  const word = line.toString('latin1', 1, sp === -1 ? line.length : sp);
  const rest = () => (sp === -1 ? '' : line.toString('utf8', sp + 1));
  switch (word) {
    case 'output': {
      if (sp === -1) return { type: 'output', pane: '', data: Buffer.alloc(0) };
      const sp2 = line.indexOf(0x20, sp + 1);
      if (sp2 === -1) return { type: 'output', pane: line.toString('latin1', sp + 1), data: Buffer.alloc(0) };
      return { type: 'output', pane: line.toString('latin1', sp + 1, sp2), data: unescapeOctal(line.subarray(sp2 + 1)) };
    }
    case 'extended-output': {
      // %extended-output %<pane> <age> ... : <data>
      const sp2 = line.indexOf(0x20, sp + 1);
      const sep = line.indexOf(Buffer.from(' : '), sp + 1);
      if (sp2 === -1 || sep === -1) return { type: 'notify', name: word, rest: rest() };
      return { type: 'output', pane: line.toString('latin1', sp + 1, sp2), data: unescapeOctal(line.subarray(sep + 3)) };
    }
    case 'begin':
    case 'end':
    case 'error': {
      const [time, num, flags] = rest().split(' ');
      return { type: word, time, num, flags: Number(flags) || 0 };
    }
    case 'exit':
      return { type: 'exit', reason: rest() };
    default:
      return { type: 'notify', name: word, rest: rest() };
  }
}

/**
 * The tmux session backend. Sessions live in Clawdling's own tmux server, so they outlive the
 * Clawdling server and are reattached when it starts again. server/pty.js is the other backend;
 * both offer the surface sessions.js uses (listSessions ... control()).
 */
export class Tmux {
  /** @param {{bin?: string, socket: string, conf: string, env?: object}} opts */
  constructor({ bin = 'tmux', socket, conf, env = process.env }) {
    this.kind = 'tmux';
    this.persistent = true; // sessions keep running when the Clawdling server stops
    this.launcher = true; // sessions run a generated /bin/sh launcher (see buildLauncherScript)
    this.bin = bin;
    this.socket = socket;
    this.conf = conf;
    this.env = env;
  }

  /** Write the config and apply it to a tmux server an older config may have started. */
  async init() {
    this.writeConf();
    await this.exec(['set-option', '-g', 'focus-events', 'on']).catch(() => {});
  }

  /** Why a session cannot start right now (null when it can). */
  missing(envPath = this.env.PATH || '') {
    return which(this.bin, envPath) ? null : `tmux not found on PATH: install tmux 3.2 or newer (${tmuxInstallHint()}), or restart Clawdling to run sessions in its built-in terminal`;
  }

  /** What `clawdling attach` / the cockpit's "copy attach command" runs. */
  attachCommand(rec) {
    return `tmux -L ${this.socket} attach -t ${rec.tmux_name}`;
  }

  /** For server.json and /api/health. */
  describe() {
    return { kind: 'tmux', socket: this.socket, persistent: true };
  }

  /** Sessions keep running in tmux when the server stops: nothing to do. */
  async shutdown() {}

  writeConf() {
    writeFileAtomic(this.conf, TMUX_CONF, 0o600);
  }

  args(...rest) {
    return ['-L', this.socket, '-f', this.conf, ...rest];
  }

  exec(args, opts = {}) {
    return execFileP(this.bin, this.args(...args), { timeout: 10000, env: this.env, ...opts });
  }

  async version() {
    try {
      const { stdout } = await execFileP(this.bin, ['-V'], { timeout: 5000, env: this.env });
      const m = stdout.match(/tmux\s+(?:next-)?(\d+)\.(\d+)/);
      return { ok: true, version: stdout.trim(), major: m ? Number(m[1]) : null, minor: m ? Number(m[2]) : null };
    } catch (e) {
      return { ok: false, version: null, error: e.code === 'ENOENT' ? 'tmux not found on PATH' : String(e.message) };
    }
  }

  static noServer(err) {
    return /no server running|error connecting|failed to connect|No such file or directory|server exited/i.test(
      String(err?.stderr || err?.message || '')
    );
  }

  /** [{name, id, pane, sid, agent}] for every session on our socket ([] when no server runs). */
  async listSessions() {
    try {
      const fmt = '#{session_name}\t#{session_id}\t#{pane_id}\t#{@clawdling_sid}\t#{@clawdling_agent}';
      const { stdout } = await this.exec(['list-sessions', '-F', fmt]);
      return stdout
        .split('\n')
        .filter(Boolean)
        .map((l) => {
          const [name, id, pane, sid, agent] = l.split('\t');
          return { name, id, pane, sid: sid || null, agent: agent || null };
        });
    } catch (err) {
      if (Tmux.noServer(err) || err.code === 'ENOENT') return [];
      throw err;
    }
  }

  async hasSession(name) {
    try {
      await this.exec(['has-session', '-t', `=${name}`]);
      return true;
    } catch {
      return false;
    }
  }

  async newSession({ name, cols, rows, command }) {
    const { stdout } = await this.exec([
      'new-session', '-d', '-s', name, '-x', String(cols), '-y', String(rows),
      '-P', '-F', '#{session_id} #{pane_id}', ...command,
    ]);
    const [sessionId, paneId] = stdout.trim().split(/\s+/);
    return { sessionId, paneId };
  }

  /** Set options on one session in a single tmux invocation (values must be our own safe strings). */
  async setOptions(name, pairs) {
    const args = [];
    for (const [k, v] of pairs) {
      if (args.length) args.push(';');
      args.push('set-option', '-t', `=${name}:`, k, String(v));
    }
    try {
      await this.exec(args);
    } catch {
      // the session may already be gone; callers notice via the control client
    }
  }

  async killSession(name) {
    try {
      await this.exec(['kill-session', '-t', `=${name}`]);
      return true;
    } catch {
      return false;
    }
  }

  async resizeWindow(name, cols, rows) {
    try {
      await this.exec(['resize-window', '-t', `=${name}:`, '-x', String(cols), '-y', String(rows)]);
    } catch {
      // ignore
    }
  }

  /** The rendered screen as plain text (no escapes, wrapped lines joined). */
  async screenText(target) {
    const { stdout } = await this.exec(['capture-pane', '-p', '-J', '-t', target]);
    return stdout;
  }

  async capture(target, history = 2000) {
    const { stdout } = await this.exec(['capture-pane', '-p', '-e', '-J', '-S', `-${history}`, '-t', target]);
    return stdout;
  }

  /** Paste text into a pane the way a terminal would (bracketed paste when the app asked for it). */
  async paste(target, text) {
    const buffer = `clawdling-${crypto.randomBytes(6).toString('hex')}`;
    await this.exec(['load-buffer', '-b', buffer, '-'], { input: text });
    await this.exec(['paste-buffer', '-b', buffer, '-p', '-d', '-t', target]);
  }

  async sendKeysHex(target, bytes) {
    for (let i = 0; i < bytes.length; i += 256) {
      const part = bytes.subarray(i, i + 256);
      await this.exec(['send-keys', '-t', target, '-H', ...Array.from(part, (b) => b.toString(16).padStart(2, '0'))]);
    }
  }

  async killServer() {
    try {
      await this.exec(['kill-server']);
    } catch {
      // not running
    }
  }

  control(name, paneId) {
    return new ControlClient(this, name, paneId);
  }
}

/**
 * One tmux control-mode client attached to one session.
 * Events: 'output' (decoded string), 'close' ({code, signal, reason}).
 */
export class ControlClient extends EventEmitter {
  constructor(tmux, name, paneId) {
    super();
    this.name = name;
    this.paneId = paneId || null;
    this.splitter = new LineSplitter();
    this.utf8 = new TextDecoder('utf-8');
    this.pending = []; // FIFO of {cb} for commands we wrote (flags=1 blocks)
    this.block = null;
    this.keyQueue = [];
    this.keyTimer = null;
    this.closed = false;
    this.exitReason = '';
    this.proc = spawn(tmux.bin, tmux.args('-C', 'attach-session', '-t', `=${name}`), {
      stdio: ['pipe', 'pipe', 'pipe'],
      env: tmux.env,
    });
    this.proc.stdout.on('data', (chunk) => {
      for (const line of this.splitter.push(chunk)) this._line(line);
    });
    this.proc.stderr.on('data', (d) => {
      this.stderr = (this.stderr || '') + d.toString();
    });
    this.proc.stdin.on('error', () => {});
    this.proc.on('error', (err) => this._closed({ error: err }));
    this.proc.on('exit', (code, signal) => this._closed({ code, signal }));
  }

  _closed(info) {
    if (this.closed) return;
    this.closed = true;
    if (this.keyTimer) clearTimeout(this.keyTimer);
    const err = new Error('control client closed');
    for (const p of this.pending.splice(0)) p.cb(err, []);
    this.emit('close', { ...info, reason: this.exitReason, stderr: this.stderr || '' });
  }

  _line(line) {
    if (this.block) {
      if (line[0] === 0x25) {
        const text = line.toString('latin1');
        const tail = ` ${this.block.time} ${this.block.num} ${this.block.flags}`;
        if (text === `%end${tail}` || text === `%error${tail}`) {
          const b = this.block;
          this.block = null;
          if (b.flags & 1) {
            const p = this.pending.shift();
            if (p) p.cb(text.startsWith('%error') ? new Error(b.lines.join('\n') || 'tmux error') : null, b.lines);
          }
          return;
        }
      }
      this.block.lines.push(line.toString('utf8'));
      return;
    }
    const msg = parseControlLine(line);
    switch (msg.type) {
      case 'begin':
        this.block = { time: msg.time, num: msg.num, flags: msg.flags, lines: [] };
        break;
      case 'output':
        if (this.paneId && msg.pane !== this.paneId) return;
        if (msg.data.length) {
          const text = this.utf8.decode(msg.data, { stream: true });
          if (text) this.emit('output', text);
        }
        break;
      case 'exit':
        this.exitReason = msg.reason || '';
        break;
      default:
        break;
    }
  }

  /** Write one command; `cb(err, lines)` runs synchronously when its response block ends. */
  command(line, cb = () => {}) {
    if (this.closed) {
      cb(new Error('control client closed'), []);
      return false;
    }
    this.pending.push({ cb });
    this.proc.stdin.write(line + '\n');
    return true;
  }

  request(line) {
    return new Promise((resolve, reject) => this.command(line, (err, lines) => (err ? reject(err) : resolve(lines))));
  }

  /** Queue raw input bytes; flushed as `send-keys -H` every 8 ms. */
  sendBytes(buf) {
    if (this.closed || !buf.length) return;
    this.keyQueue.push(buf);
    if (!this.keyTimer) this.keyTimer = setTimeout(() => this._flushKeys(), 8);
  }

  _flushKeys() {
    this.keyTimer = null;
    const all = Buffer.concat(this.keyQueue);
    this.keyQueue = [];
    const target = this.paneId || `=${this.name}:`;
    for (let i = 0; i < all.length; i += 256) {
      const part = all.subarray(i, i + 256);
      const hex = Array.from(part, (b) => b.toString(16).padStart(2, '0')).join(' ');
      this.command(`send-keys -t ${target} -H ${hex}`);
    }
  }

  resize(cols, rows) {
    this.command(`refresh-client -C ${cols}x${rows}`);
  }

  /**
   * Make the window cols x rows (the session is `window-size manual`). done(true) once tmux has
   * applied it; done(false) when it already was that size or this client is gone. Everything goes
   * through this client, so it is ordered with a snapshot taken after it.
   */
  fit(cols, rows, done) {
    if (this.closed) {
      done(false);
      return;
    }
    const target = this.paneId || `=${this.name}:`;
    this.command(`display-message -p -t ${target} '#{window_width} #{window_height}'`, (err, lines) => {
      const [w, h] = String((lines && lines[0]) || '').trim().split(/\s+/).map(Number);
      if (!err && w === cols && h === rows) {
        done(false);
        return;
      }
      if (this.closed) {
        done(false);
        return;
      }
      this.command(`resize-window -t =${this.name}: -x ${cols} -y ${rows}`);
      // The reply to the last command means tmux has resized its grid.
      this.command(`refresh-client -C ${cols}x${rows}`, () => done(true));
    });
  }

  /**
   * The screen plus 2000 lines of history, the cursor and the replayed modes, captured through this
   * client so the snapshot is an exact cut of the output stream: cb(data), or cb(null) on failure.
   */
  snapshot(modes, cb) {
    const target = this.paneId || `=${this.name}:`;
    let captured = null;
    this.command(`capture-pane -p -e -J -S -2000 -t ${target}`, (err, lines) => {
      captured = err ? null : lines;
    });
    this.command(`display-message -p -t ${target} '#{cursor_x} #{cursor_y} #{pane_width} #{pane_height} #{cursor_flag} #{alternate_on}'`, (err, lines) => {
      cb(captured ? buildSnapshot(captured, err ? '' : lines[0], modes) : null);
    });
  }

  close() {
    if (this.closed) return;
    try {
      this.proc.stdin.end();
    } catch {
      // ignore
    }
    const t = setTimeout(() => {
      if (!this.closed) this.proc.kill('SIGTERM');
    }, 1000);
    t.unref?.();
  }
}

/** Remove a stale socket file left behind by a crashed or killed tmux server (tests). */
export function socketPath(socket, env = process.env) {
  const uid = typeof process.getuid === 'function' ? process.getuid() : 0;
  return `${env.TMUX_TMPDIR || '/tmp'}/tmux-${uid}/${socket}`;
}

export function removeSocketFile(socket, env = process.env) {
  try {
    fs.unlinkSync(socketPath(socket, env));
  } catch {
    // gone already
  }
}
