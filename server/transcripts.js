// Chat view of a session, read from Claude Code's own transcript JSONL
// (${CLAUDE_CONFIG_DIR:-~/.claude}/projects/<cwd-slug>/<session-id>.jsonl). Read-only, local.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { isUuid, oneLine } from './util.js';

const PLUMBING = /^\s*<(?:command-name|command-message|command-args|local-command-stdout|local-command-stderr|local-command-caveat|bash-input|bash-stdout|bash-stderr|system-reminder|user-memory-input)>/;
const CAVEAT = /^Caveat: The messages below were generated by the user while running local commands/;
const SUMMARY_KEYS = ['command', 'file_path', 'pattern', 'url', 'description', 'path', 'query', 'prompt', 'skill'];

export function claudeConfigDir(env = process.env) {
  return env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude');
}

export function toolSummary(input) {
  if (!input || typeof input !== 'object') return '';
  for (const k of SUMMARY_KEYS) {
    if (typeof input[k] === 'string' && input[k].trim()) return oneLine(input[k], 80);
  }
  return '';
}

/** One transcript line → a chat entry {role, text, tools, ts}, or null when it is not chat. */
export function transcriptEntry(o) {
  if (!o || typeof o !== 'object' || o.isMeta || o.isSidechain) return null;
  if (o.type !== 'user' && o.type !== 'assistant') return null;
  const msg = o.message;
  if (!msg || typeof msg !== 'object') return null;
  const ts = typeof o.timestamp === 'string' ? o.timestamp : null;
  if (o.type === 'user') {
    let text = '';
    if (typeof msg.content === 'string') text = msg.content;
    else if (Array.isArray(msg.content)) {
      if (!msg.content.some((b) => b?.type === 'text')) return null; // tool_result-only turns
      text = msg.content.filter((b) => b?.type === 'text' && typeof b.text === 'string').map((b) => b.text).join('\n');
    }
    text = text.trim();
    if (!text || PLUMBING.test(text) || CAVEAT.test(text)) return null;
    return { role: 'user', text, tools: [], ts };
  }
  if (msg.model === '<synthetic>') return null;
  const blocks = Array.isArray(msg.content) ? msg.content : typeof msg.content === 'string' ? [{ type: 'text', text: msg.content }] : [];
  const text = blocks
    .filter((b) => b?.type === 'text' && typeof b.text === 'string')
    .map((b) => b.text)
    .join('\n')
    .trim();
  const tools = blocks.filter((b) => b?.type === 'tool_use').map((b) => ({ name: String(b.name || 'tool'), summary: toolSummary(b.input) }));
  if (!text && !tools.length) return null;
  return { role: 'assistant', text, tools, ts };
}

/** Locate a session's transcript. Ids are validated UUIDs, so the path can't escape projects/. */
export function findTranscript({ ids = [], hint = null, configDir }) {
  const projects = path.join(configDir, 'projects');
  if (typeof hint === 'string' && /[\\/]projects[\\/][^\\/]+[\\/][0-9a-f-]{36}\.jsonl$/.test(hint) && ids.includes(path.basename(hint, '.jsonl'))) {
    if (fs.existsSync(hint)) return hint;
  }
  let dirs = [];
  try {
    dirs = fs.readdirSync(projects);
  } catch {
    return null;
  }
  for (const id of ids) {
    if (!isUuid(id)) continue;
    for (const d of dirs) {
      const f = path.join(projects, d, `${id}.jsonl`);
      if (fs.existsSync(f)) return f;
    }
  }
  return null;
}

/** Incremental reader: re-reads only what was appended since the last call. */
export class TranscriptReader {
  constructor({ maxFiles = 64 } = {}) {
    this.cache = new Map();
    this.maxFiles = maxFiles;
  }

  read(file) {
    let st;
    try {
      st = fs.statSync(file);
    } catch {
      return [];
    }
    let c = this.cache.get(file);
    if (!c || st.size < c.offset || st.ino !== c.ino) c = { offset: 0, ino: st.ino, rest: Buffer.alloc(0), entries: [] };
    if (st.size > c.offset) {
      const fd = fs.openSync(file, 'r');
      try {
        const buf = Buffer.alloc(st.size - c.offset);
        fs.readSync(fd, buf, 0, buf.length, c.offset);
        c.offset = st.size;
        const all = c.rest.length ? Buffer.concat([c.rest, buf]) : buf;
        const nl = all.lastIndexOf(0x0a);
        const complete = nl === -1 ? '' : all.subarray(0, nl).toString('utf8');
        c.rest = Buffer.from(nl === -1 ? all : all.subarray(nl + 1));
        for (const line of complete.split('\n')) {
          if (!line.trim()) continue;
          let o;
          try {
            o = JSON.parse(line);
          } catch {
            continue;
          }
          const e = transcriptEntry(o);
          if (e) c.entries.push({ n: c.entries.length, ...e });
        }
      } finally {
        fs.closeSync(fd);
      }
    }
    this.cache.delete(file);
    this.cache.set(file, c);
    while (this.cache.size > this.maxFiles) this.cache.delete(this.cache.keys().next().value);
    return c.entries;
  }
}
