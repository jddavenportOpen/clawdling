// Chat view of a session, read from Claude Code's own transcript JSONL
// (${CLAUDE_CONFIG_DIR:-~/.claude}/projects/<cwd-slug>/<session-id>.jsonl). Read-only, local.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { isUuid, oneLine } from './util.js';

const PLUMBING = /^\s*<(?:command-name|command-message|command-args|local-command-stdout|local-command-stderr|local-command-caveat|bash-input|bash-stdout|bash-stderr|system-reminder|user-memory-input)>/;
const CAVEAT = /^Caveat: The messages below were generated by the user while running local commands/;
const SUMMARY_KEYS = ['command', 'file_path', 'pattern', 'url', 'description', 'path', 'query', 'prompt', 'skill'];

export function claudeConfigDir(env = process.env) {
  return env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude');
}

const DETAIL_MAX = 2000;

/** The full tool input for the chat view's expanded line: a command or path as is, else JSON. */
export function toolDetail(input) {
  if (input === undefined || input === null) return '';
  let text;
  if (typeof input !== 'object') text = String(input);
  else {
    const keys = Object.keys(input);
    if (keys.length === 1 && typeof input[keys[0]] === 'string') text = input[keys[0]];
    else {
      try {
        text = JSON.stringify(input, null, 2);
      } catch {
        text = '';
      }
    }
  }
  return text.length > DETAIL_MAX ? `${text.slice(0, DETAIL_MAX)}…` : text;
}

export function toolSummary(input) {
  if (!input || typeof input !== 'object') return '';
  // A question Claude asked (AskUserQuestion): the question itself, in plain words.
  if (Array.isArray(input.questions) && input.questions.length) {
    const qs = input.questions.map((q) => (q && typeof q.question === 'string' ? q.question : '')).filter(Boolean);
    if (qs.length) return cut(qs.join(' / '), 80);
  }
  for (const k of SUMMARY_KEYS) {
    if (typeof input[k] === 'string' && input[k].trim()) return cut(input[k], 80);
  }
  return '';
}

/** One line, at most `max` characters, ending in … when it was cut. */
function cut(s, max) {
  const t = oneLine(s, max + 1);
  return t.length > max ? `${t.slice(0, max - 1)}…` : t;
}

// Claude asking the person something in the chat (answered with a question card, see askOf).
export const ASK_TOOLS = { AskUserQuestion: 'question', ExitPlanMode: 'plan' };
const ASK_LIMITS = { questions: 4, options: 12, question: 600, header: 80, label: 200, description: 600, plan: 20000 };

const clipText = (v, max) => (typeof v === 'string' ? (v.length > max ? `${v.slice(0, max - 1)}…` : v) : '');

/** What a question card needs from an AskUserQuestion / ExitPlanMode input, bounded; null if unusable. */
export function askOf(name, input) {
  const kind = ASK_TOOLS[name];
  if (!kind || !input || typeof input !== 'object') return null;
  if (kind === 'plan') return { kind, plan: clipText(input.plan, ASK_LIMITS.plan) };
  if (!Array.isArray(input.questions)) return null;
  const questions = input.questions.slice(0, ASK_LIMITS.questions).map((q) => ({
    question: clipText(q?.question, ASK_LIMITS.question),
    header: clipText(q?.header, ASK_LIMITS.header),
    multiSelect: q?.multiSelect === true,
    options: (Array.isArray(q?.options) ? q.options : []).slice(0, ASK_LIMITS.options).map((o) => ({ label: clipText(o?.label, ASK_LIMITS.label), description: clipText(o?.description, ASK_LIMITS.description) })),
  }));
  if (!questions.length || questions.some((q) => !q.question || !q.options.length)) return null;
  return { kind, questions };
}

// Claude Code 2.1.308 calls ExitPlanMode with an empty input and keeps the plan in its plan file,
// <config dir>/plans/<slug>.md, written (Write) and revised (Edit) just before. The plan card reads
// it from there (issue #21): only a .md file whose real path is inside that plans folder.
const PLAN_FILE_RE = /[\\/]plans[\\/][^\\/]+\.md$/i;
const PLAN_FILE_MAX = 1024 * 1024;

/** The Claude Code config folder a transcript lives in: <config>/projects/<project>/<sid>.jsonl. */
export function configDirOfTranscript(file) {
  return typeof file === 'string' && file ? path.resolve(path.dirname(file), '..', '..') : null;
}

/** The text of a plan file, if it is a .md file inside <configDir>/plans (by real path), else null. */
export function readPlanFile(configDir, file) {
  if (!configDir || typeof file !== 'string' || !PLAN_FILE_RE.test(file)) return null;
  try {
    const dir = fs.realpathSync(path.join(configDir, 'plans'));
    const real = fs.realpathSync(file);
    if (path.dirname(real) !== dir || !real.toLowerCase().endsWith('.md')) return null;
    const st = fs.statSync(real);
    if (!st.isFile() || st.size > PLAN_FILE_MAX) return null;
    return fs.readFileSync(real, 'utf8');
  } catch {
    return null;
  }
}

/**
 * Follow a transcript's writes to its plan file, so an ExitPlanMode with an empty input still has a
 * plan: `state` is {path, text}; returns it updated for one record.
 */
export function trackPlanFile(state, o, configDir) {
  // 2.1.308 puts the plan's name on every line (`slug`): <config>/plans/<slug>.md.
  if (o && typeof o.slug === 'string' && /^[A-Za-z0-9][A-Za-z0-9._-]{0,120}$/.test(o.slug)) state = { ...(state || {}), slug: o.slug };
  if (!o || o.type !== 'assistant' || o.isSidechain || !Array.isArray(o.message?.content)) return state;
  for (const b of o.message.content) {
    if (b?.type !== 'tool_use' || !b.input || typeof b.input !== 'object') continue;
    const f = b.input.file_path;
    // Only Claude Code's own plans folder for this transcript (never a repo's docs/plans/x.md).
    if (typeof f !== 'string' || !PLAN_FILE_RE.test(f) || !configDir || path.resolve(path.dirname(f)) !== path.resolve(configDir, 'plans')) continue;
    if (b.name === 'Write' && typeof b.input.content === 'string') state = { ...(state || {}), path: f, text: b.input.content };
    else if (b.name === 'Edit' || b.name === 'MultiEdit') {
      // The edit's result is on disk: read the file (inside the plans folder only), at this line.
      const text = readPlanFile(configDir, f);
      state = { ...(state || {}), path: f, text: text ?? (state && state.path === f ? state.text : null) };
    }
  }
  return state;
}

/**
 * A plan card's text: the input's plan, else the plan file the transcript last wrote. `live` (the
 * hook, as the plan is shown): the file as it is now; otherwise (reading a transcript, perhaps much
 * later) the text the file had at that line, so an old card never shows a newer plan.
 */
export function planText(input, state, configDir, { live = false } = {}) {
  const own = input && typeof input.plan === 'string' ? input.plan : '';
  if (own.trim()) return own;
  // A plan-file path in the input (a possible future shape) is read the same confined way.
  for (const k of ['planFilePath', 'plan_file_path', 'planFile', 'plan_path']) {
    const t = input && typeof input[k] === 'string' ? readPlanFile(configDir, input[k]) : null;
    if (t && t.trim()) return t;
  }
  if (state && state.path) {
    const disk = live ? readPlanFile(configDir, state.path) : null;
    if (disk && disk.trim()) return disk;
    if (state.text && state.text.trim()) return state.text;
  }
  // The hook can arrive before the Write is in the transcript: the file its slug names.
  if (state && state.slug && configDir) {
    const t = readPlanFile(configDir, path.join(configDir, 'plans', `${state.slug}.md`));
    if (t && t.trim()) return t;
  }
  return '';
}

/**
 * The answer a person gave a question or plan, from the tool_result line: {answers} for a
 * question ({question text: answer}), {approved: true} or {feedback} for a plan, {declined: true}.
 */
export function askAnswerOf(kind, block, toolUseResult) {
  const text = typeof block?.content === 'string' ? block.content : Array.isArray(block?.content) ? block.content.filter((b) => b?.type === 'text').map((b) => b.text).join('\n') : '';
  if (kind === 'question') {
    const a = toolUseResult && typeof toolUseResult === 'object' && toolUseResult.answers && typeof toolUseResult.answers === 'object' ? toolUseResult.answers : null;
    if (a && block?.is_error !== true) {
      const answers = {};
      for (const [k, v] of Object.entries(a).slice(0, ASK_LIMITS.questions)) answers[clipText(k, ASK_LIMITS.question)] = clipText(String(v), ASK_LIMITS.label * 4);
      return { answers };
    }
    return { declined: true };
  }
  if (block?.is_error !== true) return { approved: true };
  const said = /the user said:\n([\s\S]*)$/.exec(text);
  return said ? { feedback: clipText(said[1].trim(), 2000) } : { declined: true };
}

// Claude Code's own bookkeeping lines for a step the person said no to, in plain words.
const INTERRUPTED = /^\[Request interrupted by user(?: for tool use)?\]$/;

/** One transcript line → a chat entry {role, text, tools, ts}, or null when it is not chat. */
export function transcriptEntry(o) {
  if (!o || typeof o !== 'object' || o.isMeta || o.isSidechain) return null;
  if (o.type !== 'user' && o.type !== 'assistant') return null;
  const msg = o.message;
  if (!msg || typeof msg !== 'object') return null;
  const ts = typeof o.timestamp === 'string' ? o.timestamp : null;
  if (o.type === 'user') {
    let text = '';
    if (typeof msg.content === 'string') text = msg.content;
    else if (Array.isArray(msg.content)) {
      if (!msg.content.some((b) => b?.type === 'text')) return null; // tool_result-only turns
      text = msg.content.filter((b) => b?.type === 'text' && typeof b.text === 'string').map((b) => b.text).join('\n');
    }
    text = text.trim();
    if (!text || PLUMBING.test(text) || CAVEAT.test(text)) return null;
    if (INTERRUPTED.test(text)) text = 'You stopped that step.';
    return { role: 'user', text, tools: [], ts };
  }
  if (msg.model === '<synthetic>') return null;
  const blocks = Array.isArray(msg.content) ? msg.content : typeof msg.content === 'string' ? [{ type: 'text', text: msg.content }] : [];
  const text = blocks
    .filter((b) => b?.type === 'text' && typeof b.text === 'string')
    .map((b) => b.text)
    .join('\n')
    .trim();
  const tools = blocks.filter((b) => b?.type === 'tool_use').map((b) => {
    const t = { name: String(b.name || 'tool'), summary: toolSummary(b.input), detail: toolDetail(b.input) };
    const ask = askOf(t.name, b.input);
    if (ask && typeof b.id === 'string') Object.assign(t, { id: b.id.slice(0, 100), ask });
    return t;
  });
  if (!text && !tools.length) return null;
  const model = typeof msg.model === 'string' && msg.model ? msg.model : null;
  return { role: 'assistant', text, tools, ts, model };
}

/** Locate a session's transcript. Ids are validated UUIDs, so the path can't escape projects/. */
export function findTranscript({ ids = [], hint = null, configDir }) {
  const projects = path.join(configDir, 'projects');
  if (typeof hint === 'string' && /[\\/]projects[\\/][^\\/]+[\\/][0-9a-f-]{36}\.jsonl$/.test(hint) && ids.includes(path.basename(hint, '.jsonl'))) {
    if (fs.existsSync(hint)) return hint;
  }
  let dirs = [];
  try {
    dirs = fs.readdirSync(projects);
  } catch {
    return null;
  }
  for (const id of ids) {
    if (!isUuid(id)) continue;
    for (const d of dirs) {
      const f = path.join(projects, d, `${id}.jsonl`);
      if (fs.existsSync(f)) return f;
    }
  }
  return null;
}

/** Incremental reader: re-reads only what was appended since the last call. */
export class TranscriptReader {
  constructor({ maxFiles = 64 } = {}) {
    this.cache = new Map();
    this.maxFiles = maxFiles;
  }

  read(file) {
    let st;
    try {
      st = fs.statSync(file);
    } catch {
      return [];
    }
    let c = this.cache.get(file);
    if (!c || st.size < c.offset || st.ino !== c.ino) c = { offset: 0, ino: st.ino, rest: Buffer.alloc(0), entries: [], asks: new Map(), plan: null };
    const configDir = configDirOfTranscript(file);
    if (st.size > c.offset) {
      const fd = fs.openSync(file, 'r');
      try {
        const buf = Buffer.alloc(st.size - c.offset);
        fs.readSync(fd, buf, 0, buf.length, c.offset);
        c.offset = st.size;
        const all = c.rest.length ? Buffer.concat([c.rest, buf]) : buf;
        const nl = all.lastIndexOf(0x0a);
        const complete = nl === -1 ? '' : all.subarray(0, nl).toString('utf8');
        c.rest = Buffer.from(nl === -1 ? all : all.subarray(nl + 1));
        for (const line of complete.split('\n')) {
          if (!line.trim()) continue;
          let o;
          try {
            o = JSON.parse(line);
          } catch {
            continue;
          }
          c.plan = trackPlanFile(c.plan, o, configDir);
          const e = transcriptEntry(o);
          // An empty ExitPlanMode (2.1.308): the plan from the plan file the session just wrote.
          if (e) for (const t of e.tools || []) if (t.ask && t.ask.kind === 'plan' && !t.ask.plan) t.ask.plan = clipText(planText({}, c.plan, configDir), ASK_LIMITS.plan);
          if (e) {
            c.entries.push({ n: c.entries.length, ...e });
            for (const t of e.tools || []) if (t.ask) c.asks.set(t.id, { kind: t.ask.kind, answered: false });
          } else {
            const a = this.answerEntry(o, c.asks);
            if (a) c.entries.push({ n: c.entries.length, ...a });
          }
        }
      } finally {
        fs.closeSync(fd);
      }
    }
    this.cache.delete(file);
    this.cache.set(file, c);
    while (this.cache.size > this.maxFiles) this.cache.delete(this.cache.keys().next().value);
    return c.entries;
  }

  /** The plan a transcript's ExitPlanMode would show now (its plan file), for the hook path. */
  planFor(file, input = {}) {
    this.read(file);
    const c = this.cache.get(file);
    return clipText(planText(input, c ? c.plan : null, configDirOfTranscript(file), { live: true }), ASK_LIMITS.plan);
  }

  /** A tool_result answering a question or plan seen earlier in the file: an `answer` chat entry. */
  answerEntry(o, asks) {
    if (!o || o.type !== 'user' || o.isSidechain || !Array.isArray(o.message?.content)) return null;
    for (const b of o.message.content) {
      if (b?.type !== 'tool_result' || typeof b.tool_use_id !== 'string') continue;
      const ask = asks.get(b.tool_use_id);
      if (!ask || ask.answered) continue;
      ask.answered = true;
      return { role: 'answer', tool_id: b.tool_use_id, kind: ask.kind, ...askAnswerOf(ask.kind, b, o.toolUseResult), text: '', tools: [], ts: typeof o.timestamp === 'string' ? o.timestamp : null };
    }
    return null;
  }

  /** The question or plan in `file` still waiting for its answer (the newest one), or null. */
  pendingAsk(file) {
    const entries = this.read(file);
    const c = this.cache.get(file);
    if (!c) return null;
    for (let i = entries.length - 1; i >= 0; i--) {
      const e = entries[i];
      if (e.role === 'answer') return null; // the newest ask was answered
      const t = (e.tools || []).findLast((x) => x.ask);
      if (t) return c.asks.get(t.id)?.answered ? null : { tool_id: t.id, ...t.ask };
      if (e.role === 'user') return null; // a newer prompt: nothing is pending
    }
    return null;
  }
}
